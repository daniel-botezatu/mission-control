#!/usr/bin/env python3
"""Prepare native host packages and safely apply/remove their owned configuration.

Python is needed only while installing/updating, never for monitoring or MCP.
No credentials are read. No network or host commands are executed by this script.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parent
OWNER = "mission-control-developer-memory-v1"
BEGIN = "# BEGIN " + OWNER
END = "# END " + OWNER
VERSION = "0.4.13"
TOOLS = json.loads((ROOT / "shared/read-tools.json").read_text(encoding="utf-8"))
DESCRIPTION = "Retrieve approved coding history and correlate read-only GitHub and Slack evidence."


def dump(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def absolute(value, label):
    path = Path(value)
    if not path.is_absolute():
        raise ValueError(label + " must be an absolute path")
    safe_tree(path)
    return path.resolve()


def safe_tree(path):
    """Reject symlinks and junctions in every existing ancestor before writing."""
    for candidate in [path, *path.parents]:
        try:
            info = candidate.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
            raise ValueError("Refusing a symbolic link or junction in the output path")


def write_atomic(path, text):
    safe_tree(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".mission-control-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def owned_files(output, files):
    """Update only files previously generated by us and still byte-identical."""
    safe_tree(output)
    manifest = output / ".mission-control-owned.json"
    safe_tree(manifest)
    previous = {}
    if manifest.exists():
        state = json.loads(manifest.read_text(encoding="utf-8"))
        if state.get("owner") != OWNER:
            raise ValueError("Output ownership does not match")
        previous = state["files"]
    for name in set(files) | set(previous):
        path = output / name
        if path.resolve().parent != output.resolve() and output.resolve() not in path.resolve().parents:
            raise ValueError("Owned path escapes package directory")
        safe_tree(path)
        if path.exists() and (name not in previous or digest(path.read_bytes()) != previous[name]):
            raise ValueError("Existing or edited file would be overwritten: " + name)
    for name, text in files.items():
        write_atomic(output / name, text)
    for name in set(previous) - set(files):
        (output / name).unlink(missing_ok=True)
    write_atomic(manifest, dump({"owner": OWNER, "version": VERSION,
                                "files": {name: digest(text.encode("utf-8")) for name, text in files.items()}}))


def prepare(args):
    output = absolute(args.output, "Output")
    mcp = absolute(args.mcp, "MCP executable")
    data = absolute(args.data_dir, "Data directory")
    if not mcp.is_file():
        raise ValueError("MCP executable does not exist")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]{0,127}", args.github_token_env):
        raise ValueError("GitHub token environment variable name is invalid")
    if args.slack_client_id and not re.fullmatch(r"[0-9]+\.[0-9]+", args.slack_client_id):
        raise ValueError("Slack client ID must be the numeric app client ID, not an OAuth token")
    previous = {}
    if (output / "installation.json").exists():
        candidate = json.loads((output / "installation.json").read_text(encoding="utf-8"))
        if candidate.get("owner") == OWNER:
            previous = candidate
    time_zone = getattr(args, "time_zone", None) or previous.get("timeZone", "local")
    if not re.fullmatch(r"[A-Za-z0-9_+/ -]{1,100}", time_zone):
        raise ValueError("Invalid timezone identifier")
    workflow = (ROOT / "shared/developer-memory.md").read_text(encoding="utf-8")
    workflow += "\nConfigured recap timezone: " + time_zone + ". Date-only bounds use this timezone. Pass timeZone explicitly if the user requests another zone.\n"
    preference = getattr(args, "private_slack", None)
    if preference is None and (output / "installation.json").exists():
        previous = json.loads((output / "installation.json").read_text(encoding="utf-8"))
        if previous.get("owner") == OWNER:
            preference = previous.get("privateSlack", "ask")
    preference = preference or "ask"
    if preference not in ("allow", "public", "ask"):
        raise ValueError("Unknown private Slack preference")
    workflow += "\nSaved Slack search preference: " + {
        "allow": "The user has explicitly authorised relevant private-channel and DM searches for work recaps. Reuse this permission; do not ask again. Keep searches relevant to the requested work and dates. This never authorises sending messages.",
        "public": "Search public channels only; do not search private channels or DMs.",
        "ask": "Private channels and DMs need the user's permission, and the recap runs in a fresh helper that cannot ask. Search them only when the request itself grants it (for example 'include private Slack'); otherwise search public channels only and say private Slack was not searched."
    }[preference] + "\n"
    files = {}
    local = {"command": str(mcp), "args": ["--data-dir", str(data), "--live", "--time-zone", time_zone]}
    mcp_config = {"mcpServers": {"history": local}}
    # External servers are deliberately native host configuration, not copied
    # provider implementations or credentials hidden in a plugin cache.
    github = {"type": "http", "url": "https://api.githubcopilot.com/mcp/", "headers": {
        "Authorization": "Bearer ${" + args.github_token_env + "}",
        "X-MCP-Readonly": "true", "X-MCP-Tools": ",".join(TOOLS["github"])}}
    slack = {"type": "http", "url": "https://mcp.slack.com/mcp"}
    if args.slack_client_id:
        slack["oauth"] = {"clientId": args.slack_client_id, "callbackPort": 3118}
    external = {"mcpServers": {"mission-control": local}}
    if args.github:
        external["mcpServers"]["mc_github"] = github
    # Claude's official Slack plugin is the recommended default; this explicit
    # internal-app route is generated only after a client ID was supplied.
    if args.slack_client_id:
        external["mcpServers"]["mc_slack"] = slack
    claude_prefixes = [("mission-control", "history"), ("plugin_mission-control_history", "history"), ("mc_github", "github"), ("plugin_github_github", "github"), ("github", "github"),
                       ("mc_slack", "slack"), ("slack", "slack"), ("plugin_slack_slack", "slack"), ("claude_ai_Slack", "slack")]
    claude_tools = ["ToolSearch"] + ["mcp__" + prefix + "__" + tool for prefix, group in claude_prefixes for tool in TOOLS[group]]
    for host in ["claude", "codex"]:
        base = host + "/"
        if host == "claude":
            files[base + ".claude-plugin/plugin.json"] = dump({"name": "mission-control", "version": VERSION,
                "description": DESCRIPTION, "author": {"name": "Mission Control"}})
            files[base + ".claude-plugin/marketplace.json"] = dump({"name": "mission-control-local",
                "description": DESCRIPTION, "owner": {"name": "Mission Control"}, "plugins": [{"name": "mission-control", "source": "./"}]})
            headers = "allowed-tools: " + ", ".join(["Agent(mission-control:memory-reader)"] + claude_tools) + "\n"
            files[base + "agents/memory-reader.md"] = (
                "---\nname: memory-reader\ndescription: Read approved developer history and linked work evidence without actions.\n"
                + "tools: " + ", ".join(t for t in claude_tools if t == "ToolSearch" or any(t.endswith("__" + name) for name in TOOLS["history"])) + "\ndisallowedTools: Bash, Write, Edit, NotebookEdit, Agent, Task, Skill\n---\n\n" + workflow + "\n" + (ROOT / "shared/recap-reader.md").read_text(encoding="utf-8"))
            # Recaps run in this fresh coordinator so their cost does not grow with the user's chat. It may
            # start helpers (the restricted readers); everything else it can do is read-only.
            files[base + "agents/recap-coordinator.md"] = (
                "---\nname: recap-coordinator\ndescription: Coordinate a developer-memory recap in a fresh context with restricted readers and read-only work sources.\n"
                + "tools: " + ", ".join(["Agent"] + claude_tools) + "\ndisallowedTools: Bash, Write, Edit, NotebookEdit, Skill\n---\n\n"
                + workflow + "\n" + (ROOT / "shared/recap-coordinator.md").read_text(encoding="utf-8"))
            # Slack results reach the AI directly. This hook applies Mission Control's secret filter to
            # them first, for every Slack server name (official plugin, claude.ai connector, internal app).
            files[base + "hooks/hooks.json"] = dump({"description": "Mission Control: remove secret-looking values from Slack results before the AI sees them.",
                "hooks": {"PostToolUse": [{"matcher": "mcp__.*[Ss]lack.*", "hooks": [
                    {"type": "command", "command": str(mcp), "args": ["filter-tool-output"], "timeout": 15}]}]}})
        else:
            overlay = {"name": "mission-control", "version": VERSION, "description": DESCRIPTION,
                "author": {"name": "Mission Control"}, "skills": "./skills/", "mcpServers": "./.mcp.json",
                "interface": {"displayName": "Mission Control", "shortDescription": "Read approved developer memory",
                    "longDescription": DESCRIPTION, "developerName": "Mission Control", "category": "Productivity",
                    "capabilities": ["Read"]}, "requires_local_executor": True}
            files[base + ".codex-plugin/plugin.json"] = dump(overlay)
            files[base + "plugin.json"] = dump({"$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
                "name": "mission-control", "version": VERSION, "description": DESCRIPTION,
                "extensions": {"com.openai": {"interface": overlay["interface"], "requires_local_executor": True}}})
            files[base + "mcp.json"] = dump({"$schema": "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
                "mcpServers": {"history": {"type": "stdio", **local}}})
            files[base + ".agents/plugins/marketplace.json"] = dump({"name": "mission-control-local",
                "interface": {"displayName": "Mission Control local"}, "plugins": [{"name": "mission-control",
                "source": {"source": "local", "path": "./"}, "policy": {"installation": "AVAILABLE"}}]})
            headers = ""
        files[base + ".mcp.json"] = dump(mcp_config)
        fork = "context: fork\nagent: mission-control:recap-coordinator\nbackground: false\n" if host == "claude" else ""
        files[base + "skills/developer-memory/SKILL.md"] = (
            "---\nname: developer-memory\ndescription: Recall work, decisions, promises, and unfinished tasks from approved coding history and connected work sources.\n"
            # Claude runs this skill inside the coordinator agent, which already carries the workflow;
            # repeating it here would put it in that context twice.
            + fork + headers + "---\n\n" + ("Answer the request below as the recap coordinator described in your instructions, and return the finished answer as your final message.\n\nRequest: $ARGUMENTS\n" if host == "claude" else workflow + "\n" + "Codex fallback: use the single full-message stream above for recaps. Codex supports parallel agents, but this installation does not provide a verified per-reader tool allowlist. Do not substitute a general-purpose helper or claim instructions alone enforce read-only access. Do not use an outline. Do not run CLI helpers, write ledgers, or change host permissions during recall.\n"))
    files["claude/external.mcp.json"] = dump(external)
    files["claude/read-only-agent-tools.json"] = dump(claude_tools)
    # A fragment is applied with ownership checks; no attempt is made to merge
    # or reinterpret somebody else's MCP definitions or OAuth storage.
    lines = ["# Native optional providers; credentials stay in the host/environment.",
        '[mcp_servers.mission-control]',
        'command = ' + json.dumps(str(mcp)), 'args = ' + json.dumps(local['args']),
        "enabled_tools = " + json.dumps(TOOLS["history"]), ""]
    if args.github:
        lines += ["[mcp_servers.mc_github]", 'url = "https://api.githubcopilot.com/mcp/"',
            "bearer_token_env_var = " + json.dumps(args.github_token_env),
            "enabled_tools = " + json.dumps(TOOLS["github"]),
            'http_headers = { "X-MCP-Readonly" = "true", "X-MCP-Tools" = ' + json.dumps(",".join(TOOLS["github"])) + " }", ""]
    if args.slack_client_id:
        lines += ["[mcp_servers.mc_slack]", 'url = "https://mcp.slack.com/mcp"',
            "enabled_tools = " + json.dumps(TOOLS["slack"]), "[mcp_servers.mc_slack.oauth]",
            "client_id = " + json.dumps(args.slack_client_id), "callback_port = 3118", ""]
    files["codex/config.fragment.toml"] = "\n".join(lines)
    files["installation.json"] = dump({"owner": OWNER, "version": VERSION, "mcp": str(mcp),
        "dataDirectory": str(data), "github": args.github, "slackInternalApp": bool(args.slack_client_id),
        "githubTokenEnv": args.github_token_env,
        "accountAuthenticationTested": False, "privateSlack": preference, "timeZone": time_zone})
    owned_files(output, files)
    print("Prepared separate Claude Code and Codex packages at " + str(output))
    print("No account, host configuration, or existing credential was accessed.")


def config_state(target):
    return target.with_name(target.name + ".mission-control-owned.json")


def read_state(target):
    state = config_state(target)
    if not state.exists():
        return None
    parsed = json.loads(state.read_text(encoding="utf-8"))
    if parsed.get("owner") != OWNER:
        raise ValueError("Configuration ownership does not match")
    if "pending" in parsed:
        pending = parsed["pending"]
        actual = digest(target.read_bytes()) if target.exists() else None
        if actual == pending["after"]:
            parsed = pending["next"]
        elif actual == pending["before"]:
            parsed = pending["previous"]
        else:
            raise ValueError("Interrupted configuration update was edited; restore the backup before retrying")
        if parsed is None:
            state.unlink()
        else:
            write_atomic(state, dump(parsed))
    return parsed


def recover_appended_host_tables(original, block, expected_hash):
    """Codex's TOML editor may append new tables before a trailing END comment.

    Move only those appended tables outside our markers, and only if the untouched
    original prefix still matches the exact recorded hash. Never adopt edited values.
    """
    if not block or not expected_hash:
        return original
    body = block.group().split(END, 1)[0]
    for heading in re.finditer(r"(?m)^\[", body):
        candidate = body[:heading.start()].rstrip("\r\n") + "\n" + END + "\n"
        if digest(candidate.encode()) == expected_hash:
            appended = body[heading.start():].rstrip("\r\n") + "\n"
            return original[:block.start()] + candidate + "\n" + appended + original[block.end():]
    return original


def modify_config(args, remove=False):
    target = absolute(args.target, "Target configuration")
    safe_tree(target)
    safe_tree(config_state(target))
    original = target.read_text(encoding="utf-8-sig") if target.exists() else ""
    state = read_state(target)
    previous_state = state
    if state and state.get("host") != args.host:
        raise ValueError("Configuration belongs to a different host")
    if remove and state is None:
        print("No owned configuration to remove; target unchanged.")
        return
    if args.host == "codex":
        if original.count(BEGIN) != original.count(END) or original.count(BEGIN) > 1:
            raise ValueError("Malformed managed configuration markers")
        block = re.search(re.escape(BEGIN) + r"\r?\n.*?" + re.escape(END) + r"(?:\r?\n)?", original, re.S)
        if block and state and state.get("blockHash") != digest(block.group().encode()):
            original = recover_appended_host_tables(original, block, state.get("blockHash"))
            block = re.search(re.escape(BEGIN) + r"\r?\n.*?" + re.escape(END) + r"(?:\r?\n)?", original, re.S)
        if block and (not state or state.get("blockHash") != digest(block.group().encode())):
            raise ValueError("Managed configuration was edited; refusing to replace or remove it")
        if state and not block:
            raise ValueError("Managed configuration is missing its owned block")
        remainder = original[:block.start()] + original[block.end():] if block else original
        if remove:
            updated = remainder
        else:
            bundle = absolute(args.bundle, "Bundle")
            fragment = (bundle / "codex/config.fragment.toml").read_text(encoding="utf-8")
            existing = tomllib.loads(remainder)
            incoming = tomllib.loads(fragment)
            if set(incoming.get("mcp_servers", {})) & set(existing.get("mcp_servers", {})):
                raise ValueError("A provider server name already exists outside the managed block")
            # Native plugin installation owns its policy independently from
            # our MCP block. Preserve it when updating or removing our entries.
            managed = BEGIN + "\n" + fragment.rstrip() + "\n" + END + "\n"
            updated = remainder + ("\n" if remainder and not remainder.endswith("\n") else "") + managed
            tomllib.loads(updated)
            state = {"owner": OWNER, "host": "codex", "blockHash": digest(managed.encode())}
    else:
        existing = json.loads(original) if original.strip() else {}
        if not isinstance(existing, dict) or not isinstance(existing.get("mcpServers", {}), dict):
            raise ValueError("Target must be a native Claude MCP JSON object")
        servers = existing.setdefault("mcpServers", {})
        owned = (state or {}).get("servers", {})
        for name, value in owned.items():
            if servers.get(name) != value:
                raise ValueError("Owned MCP server was edited or removed: " + name)
        incoming = {} if remove else json.loads((absolute(args.bundle, "Bundle") / "claude/external.mcp.json").read_text(encoding="utf-8"))["mcpServers"]
        for name in incoming:
            if name in servers and name not in owned:
                raise ValueError("MCP server name already exists: " + name)
        for name in owned:
            servers.pop(name)
        servers.update(incoming)
        updated = dump(existing)
        state = {"owner": OWNER, "host": "claude", "servers": incoming}
    # Save a one-time pre-install backup without replacing a previous backup.
    backup = target.with_name(target.name + ".before-mission-control")
    if target.exists() and not backup.exists() and not remove:
        safe_tree(backup)
        with backup.open("x", encoding="utf-8", newline="") as stream:
            stream.write(original)
    next_state = None if remove else state
    # A journal containing hashes and only our entries makes either side of a
    # crash recoverable without copying unrelated configuration or credentials.
    write_atomic(config_state(target), dump({"owner": OWNER, "pending": {
        "before": digest(target.read_bytes()) if target.exists() else None,
        "after": digest(updated.encode("utf-8")), "previous": previous_state, "next": next_state}}))
    write_atomic(target, updated)
    if next_state is None:
        config_state(target).unlink(missing_ok=True)
    else:
        write_atomic(config_state(target), dump(next_state))
    print(("Removed owned entries from " if remove else "Applied owned entries to ") + str(target))


def remove_package(args):
    output = absolute(args.output, "Output")
    safe_tree(output)
    manifest = output / ".mission-control-owned.json"
    safe_tree(manifest)
    state = json.loads(manifest.read_text(encoding="utf-8"))
    if state.get("owner") != OWNER:
        raise ValueError("Package ownership does not match")
    for name, expected in state["files"].items():
        path = output / name
        safe_tree(path)
        if output not in path.resolve().parents:
            raise ValueError("Owned path escapes package directory")
        if path.exists() and digest(path.read_bytes()) != expected:
            raise ValueError("Package file was edited; refusing removal: " + name)
    for name in state["files"]:
        (output / name).unlink(missing_ok=True)
    manifest.unlink()
    print("Removed owned package files; unrelated files and host registrations are untouched.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="action", required=True)
    command = commands.add_parser("prepare", help="Generate native packages; no host settings are changed")
    command.add_argument("--output", required=True)
    command.add_argument("--mcp", required=True)
    command.add_argument("--data-dir", required=True)
    command.add_argument("--time-zone", help="IANA recap timezone or local; preserves prior choice, otherwise uses the machine timezone")
    command.add_argument("--github", action="store_true", help="Generate optional official read-only GitHub configuration")
    command.add_argument("--github-token-env", default="MISSION_CONTROL_GITHUB_TOKEN")
    command.add_argument("--slack-client-id", help="Opt in to native official Slack OAuth using your registered internal app")
    command.add_argument("--private-slack", choices=["allow", "public", "ask"], help="Save the user's explicit recap search preference; preserve it on subsequent updates")
    command = commands.add_parser("remove-package", help="Remove only unchanged generated package files")
    command.add_argument("--output", required=True)
    for action in ["apply-config", "remove-config"]:
        command = commands.add_parser(action)
        command.add_argument("--host", choices=["claude", "codex"], required=True)
        command.add_argument("--target", required=True, help="Explicit absolute native configuration file")
        if action == "apply-config":
            command.add_argument("--bundle", required=True)
    args = parser.parse_args()
    try:
        if args.action == "prepare":
            prepare(args)
        elif args.action == "remove-package":
            remove_package(args)
        else:
            modify_config(args, args.action == "remove-config")
        return 0
    except (ValueError, OSError, KeyError, TypeError) as error:
        print("Mission Control integration: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
